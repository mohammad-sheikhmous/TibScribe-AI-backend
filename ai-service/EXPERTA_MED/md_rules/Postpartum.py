    def _follow7_evidence(self, codes) -> list[dict]:
        wanted = set(codes)
        evidence = []
        for fact in getattr(self, "facts", {}).values():
            if isinstance(fact, ClinicalFact) and fact.get("code") in wanted:
                evidence.append(_fact_evidence(fact))
        return evidence

    def _follow7_emit(self, rule_id: str, evidence_codes=()) -> None:
        category, rule_type, priority, confidence, title, detail, condition_text = RULE_META[rule_id]
        full_id = f"FOLLOW7-{rule_id}"
        severity = {
            "Critical": "critical",
            "High": "high",
            "Medium": "medium",
            "Low": "low",
        }.get(priority, "medium")
        self._emit(
            Suggestion(
                rule_id=full_id,
                rule_version=FOLLOW7_RULES_VERSION,
                severity=severity,
                condition=category,
                title_ar=title,
                detail_ar=detail,
                evidence=self._follow7_evidence(evidence_codes),
                chain=[
                    f"تحققت شروط القاعدة {full_id}",
                    f"الشرط السريري: {condition_text}",
                    f"الفئة: {category}؛ النوع: {rule_type}",
                    f"الأولوية: {priority}؛ قوة الدليل: {confidence}",
                    "إصدار توصية تخص النفاس أو رعاية المولود للمراجعة السريرية",
                ],
                references=[
                    f"{SOURCE_NAME} — {rule_id}",
                    f"{METADATA_NAME} — {rule_id}",
                ],
            ),
            dedupe=(full_id, category),
        )
        self.declare(RuleState(code=full_id, category=category))

